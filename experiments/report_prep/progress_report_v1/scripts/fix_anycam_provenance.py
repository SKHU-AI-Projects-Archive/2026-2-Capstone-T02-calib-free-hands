"""Correct the AnyCam provenance metadata, with an audit trail.

The CAM-EXP-004.1 provenance manifest was generated by a script that hard-coded
AnyCam as NOT_INSTALLED. By the time it ran, the official repository had in fact
been cloned and the official checkpoint downloaded, and part of the official
code had been executed for the identifiability test. Three files therefore
disagreed with each other.

Only metadata is corrected. No numerical result is touched.
"""
from __future__ import annotations

import csv
import json
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
MANIFEST = REPO / "experiments" / "manifests" / "external_model_provenance_v1.json"
CAM0041 = REPO / "experiments" / "runs" / "CAM-EXP-004_1_pre_cam005_robustness_audit"
TABLE = CAM0041 / "tables" / "external_model_provenance.csv"
REPORT = CAM0041 / "report.md"
PKG = Path(__file__).resolve().parents[1]

COMMIT = "e609cc8a9e4ee8f78cf2ce39ebeb86b35e82d10d"
CKPT_SHA = "4b2f723f6b6672a9ef3a6a4d1831c08418db498f2832c565d524e3d201c300af"
CFG_SHA = "4c978ef6e23279b56d0f21ae7a452eafdafbb4521dc82174717a7a07774d908c"

CORRECTED = {
    "repository": "https://github.com/Brummi/anycam",
    "exact_commit": COMMIT,
    "commit_resolution": "git rev-parse HEAD of the clone at "
                         "experiments/cache/external_models/anycam, made during "
                         "the CAM-EXP-004.1 static applicability audit",
    "execution_status": {
        "REPOSITORY_INSTALLED_SOURCE_AVAILABLE": True,
        "CHECKPOINT_DOWNLOADED": True,
        "END_TO_END_INFERENCE": "BLOCKED_ON_WINDOWS",
        "MECHANISTIC_IDENTIFIABILITY_TEST": "COMPLETED",
    },
    "windows_blocker": (
        "anycam/scripts/fit_video.py applies torch.compile at import, which "
        "raises 'Windows not yet supported for torch.compile' on torch <= 2.5; "
        "meanwhile the UniDepth depth backbone imports "
        "xformers.components.attention.NystromAttention, which exists only in "
        "xformers <= 0.0.28.post3 - a version with no Windows wheel that also "
        "requires torch 2.5.1. The two requirements are mutually exclusive on "
        "this platform, and satisfying them would require editing official "
        "source, which was not done."),
    "official_code_actually_executed": [
        "anycam.trainer.make_proj_from_focal_length",
        "anycam.trainer.induce_flow_dist",
    ],
    "code_path_of_the_identifiability_test":
        "the same functions anycam/scripts/fit_video.py uses to score its 32 "
        "focal candidates before proj_labels.argmax(); called unmodified on "
        "synthetic depth with identity vs translating relative poses",
    "checkpoints_used": ["anycam_v1_seq8"],
    "checkpoint_source": {
        "huggingface_repo": "fwimbauer/anycam_v1_seq8",
        "resolved_from": "the repository's own hubconf.py, which downloads "
                         "config.yaml and pytorch_model.bin from that repo id",
        "files": {
            "pytorch_model.bin": {"bytes": 459833700, "sha256": CKPT_SHA},
            "config.yaml": {"bytes": 11240, "sha256": CFG_SHA},
        },
    },
    "benchmark_status": "NOT_A_PERFORMANCE_BENCHMARK - AnyCam was never run as "
                        "a ranked baseline and produced no focal-accuracy number",
    "status": "NOT_APPLICABLE_REQUIRES_CAMERA_MOTION - the official focal "
              "selection objective is flat across all 32 candidates under a "
              "static camera (spread 2.73e-09 vs 0.223 with camera motion)",
    "license": "see repository",
    "used_in": ["CAM-EXP-004 (source audit)",
                "CAM-EXP-004.1 (mechanistic identifiability test)"],
}

OLD_SNAPSHOT = {
    "external_model_provenance_v1.json": {
        "exact_commit": None, "commit_resolution": "NOT_INSTALLED",
        "used_in": [],
    },
    "CAM-EXP-004.1/tables/external_model_provenance.csv": {
        "exact_commit": "NOT_INSTALLED", "commit_resolution": "NOT_INSTALLED",
        "checkpoints": "none", "checkpoint_sha256_first16": "", "used_in": "",
    },
    "CAM-EXP-004.1/report.md": {
        "provenance_table_cell": "fresh clone (not used for any result)",
    },
}


def main() -> None:
    man = json.loads(MANIFEST.read_text(encoding="utf-8"))
    man["models"]["AnyCam"] = CORRECTED
    man["schema_version"] = man.get("schema_version", "1.0")
    man.setdefault("corrections", []).append({
        "date": str(date.today()),
        "field": "models.AnyCam",
        "old": OLD_SNAPSHOT["external_model_provenance_v1.json"],
        "reason": "the generating script hard-coded NOT_INSTALLED; the official "
                  "repository had in fact been cloned, the official checkpoint "
                  "downloaded, and two official functions executed for the "
                  "identifiability test",
        "numerical_impact": "none - no experiment result depends on this field",
        "corrected_by": "experiments/report_prep/progress_report_v1/scripts/"
                        "fix_anycam_provenance.py",
    })
    MANIFEST.write_text(json.dumps(man, indent=2), encoding="utf-8")

    rows = list(csv.DictReader(open(TABLE, encoding="utf-8")))
    for r in rows:
        if r["model"] == "AnyCam":
            r["exact_commit"] = COMMIT
            r["commit_resolution"] = CORRECTED["commit_resolution"]
            r["checkpoints"] = "anycam_v1_seq8 (pytorch_model.bin)"
            r["checkpoint_sha256_first16"] = CKPT_SHA[:16]
            r["adapter"] = ("none - no adapter was written; AnyCam was not run "
                            "as a ranked baseline")
            r["output_convention"] = "n/a - no focal number was produced"
            r["used_in"] = ("CAM-EXP-004 (source audit);"
                            "CAM-EXP-004.1 (mechanistic identifiability test)")
    with open(TABLE, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    txt = REPORT.read_text(encoding="utf-8")
    old_cell = "| AnyCam | `e609cc8a9e4ee8f78cf2ce39ebeb86b35e82d10d` | fresh clone (not used for any result) | `fwimbauer/anycam_v1_seq8` |"
    new_cell = "| AnyCam | `e609cc8a9e4ee8f78cf2ce39ebeb86b35e82d10d` | git HEAD of the clone; two of its functions were executed for the identifiability test, no end-to-end inference | `fwimbauer/anycam_v1_seq8` |"
    if old_cell in txt:
        REPORT.write_text(txt.replace(old_cell, new_cell), encoding="utf-8")
        print("corrected the CAM-EXP-004.1 report provenance cell")
    else:
        print("WARNING: report cell not found, left unchanged")

    print("corrected AnyCam provenance in the manifest and the run table")


if __name__ == "__main__":
    main()
